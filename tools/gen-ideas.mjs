// Builds the gift ideas catalog from the plain-text lists in netlify/lib/ideas/*.txt:
//   netlify/lib/ideas-data.mjs   the products (a JS module so it is bundled into the Netlify function)
//   public/ideas/<category>.svg  a picture tile per category (ideas have no product photo)
// Each line: name|estimated price|category|extra age groups. Run: node tools/gen-ideas.mjs
import fs from 'node:fs';
import { slugify } from '../netlify/lib/product-utils.mjs';

export const AGE_FILES = { kids: 'K', tweens: 'W', teens: 'T', 'young-adults': 'Y', adults: 'A', seniors: 'S' };
export const AGE_NAMES = { K: 'kids', W: 'tweens', T: 'teens', Y: 'young-adults', A: 'adults', S: 'seniors' };

// category -> [emoji, gradient from, gradient to, quiz tags]
export const STYLE = {
  'Gaming': ['🎮', '#4338ca', '#0f172a', ['tech', 'fun']],
  'Tech & gadgets': ['🔌', '#0e7490', '#0f172a', ['tech']],
  'Audio': ['🎧', '#7c3aed', '#0f172a', ['tech']],
  'Maker & STEM': ['🛠️', '#b45309', '#0f172a', ['tech']],
  'Fashion & shoes': ['👟', '#be123c', '#0f172a', ['practical']],
  'Skincare & body': ['🧴', '#0f766e', '#0f172a', ['skin']],
  'Hair care': ['💇', '#a21caf', '#0f172a', ['hair']],
  'Fragrance': ['🌲', '#166534', '#0f172a', ['fragrance']],
  'Makeup': ['💄', '#be185d', '#0f172a', ['skin']],
  'Room & decor': ['🛋️', '#9a3412', '#0f172a', ['practical']],
  'Books & manga': ['📚', '#1d4ed8', '#0f172a', ['practical']],
  'Toys & collectibles': ['🧸', '#c2410c', '#0f172a', ['fun']],
  'Games & puzzles': ['🧩', '#15803d', '#0f172a', ['fun']],
  'Sports & outdoors': ['🚲', '#0369a1', '#0f172a', ['outdoors']],
  'Music & art': ['🎨', '#a16207', '#0f172a', ['practical']],
  'School & desk': ['✏️', '#475569', '#0f172a', ['practical']],
  'Food & drinks': ['🍿', '#b91c1c', '#0f172a', ['practical']],
  'Home & kitchen': ['☕', '#854d0e', '#0f172a', ['practical']],
  'Wellness': ['🧘', '#0d9488', '#0f172a', ['skin', 'practical']],
  'Travel & bags': ['🎒', '#1e40af', '#0f172a', ['practical']],
  'Gift cards': ['💳', '#6d28d9', '#0f172a', ['giftcard']]
};

const dir = new URL('../netlify/lib/ideas/', import.meta.url);
const byId = new Map();
const problems = [];

for (const [file, primary] of Object.entries(AGE_FILES)) {
  const lines = fs.readFileSync(new URL(`${file}.txt`, dir), 'utf8').split('\n');
  lines.forEach((raw, n) => {
    const line = raw.trim();
    if (!line || line.startsWith('#')) return;
    const [name, priceText, category, codes = ''] = line.split('|').map(x => x.trim());
    const price = Number(priceText);
    if (!name || !Number.isInteger(price) || price < 1 || price > 5000) return problems.push(`${file}.txt:${n + 1} bad price "${priceText}"`);
    if (!STYLE[category]) return problems.push(`${file}.txt:${n + 1} unknown category "${category}"`);
    const letters = [...new Set([primary, ...codes])].filter(c => AGE_NAMES[c]);
    if (codes.split('').some(c => !AGE_NAMES[c])) return problems.push(`${file}.txt:${n + 1} bad age codes "${codes}"`);
    const id = `idea_${slugify(name)}`;
    const ages = letters.map(c => AGE_NAMES[c]);
    if (byId.has(id)) {
      const cur = byId.get(id);
      cur.ages = [...new Set([...cur.ages, ...ages])]; // same idea listed for several ages
      return;
    }
    byId.set(id, {
      id,
      title: name,
      price,
      category,
      ages,
      image: `/ideas/${slugify(category)}.svg`,
      url: `https://www.amazon.com/s?k=${encodeURIComponent(name)}`,
      site: 'amazon.com',
      tags: STYLE[category][3],
      kind: 'idea',
      estimated: true
    });
  });
}

if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const items = [...byId.values()];
fs.writeFileSync(new URL('../netlify/lib/ideas-data.mjs', import.meta.url), `// GENERATED by tools/gen-ideas.mjs from netlify/lib/ideas/*.txt - do not edit by hand.\n// Ideas: real, well-known products with ESTIMATED prices and an Amazon search link (not verified listings).\nexport default ${JSON.stringify(items)};\n`);

fs.mkdirSync(new URL('../public/ideas/', import.meta.url), { recursive: true });
for (const [category, [emoji, from, to]] of Object.entries(STYLE)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300" width="400" height="300"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${from}"/><stop offset="1" stop-color="${to}"/></linearGradient></defs><rect width="400" height="300" fill="url(#g)"/><text x="200" y="165" font-size="110" text-anchor="middle" font-family="Apple Color Emoji,Segoe UI Emoji,Noto Color Emoji,sans-serif">${emoji}</text><text x="200" y="258" font-size="22" text-anchor="middle" fill="#ffffff" fill-opacity="0.75" font-family="system-ui,sans-serif" font-weight="600">${category.replace(/&/g, '&amp;')}</text></svg>\n`;
  fs.writeFileSync(new URL(`../public/ideas/${slugify(category)}.svg`, import.meta.url), svg);
}

const counts = {};
items.forEach(i => i.ages.forEach(a => { counts[a] = (counts[a] || 0) + 1; }));
console.log(`wrote ${items.length} ideas`, counts);
