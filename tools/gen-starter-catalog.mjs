// Builds netlify/lib/starter-catalog.mjs from the verified starter gifts (src/data/initialWishlist.js).
// (A plain JS module, not a JSON file read at runtime, so it is bundled into the Netlify function.)
// Run: node tools/gen-starter-catalog.mjs
import fs from 'node:fs';
import { DEFAULT_WISHLIST } from '../src/data/initialWishlist.js';
import { categoryOf, productIdOf } from '../netlify/lib/product-utils.mjs';

const items = DEFAULT_WISHLIST.map(i => ({
  id: productIdOf(i.url),
  title: i.title,
  price: i.price,
  image: i.imageUrl,
  url: i.url,
  site: new URL(i.url).hostname.replace(/^www\./, ''),
  category: categoryOf(i.tags || []),
  tags: i.tags || [],
  starter: true
}));
fs.writeFileSync(new URL('../netlify/lib/starter-catalog.mjs', import.meta.url), `// GENERATED by tools/gen-starter-catalog.mjs - do not edit by hand.\nexport default ${JSON.stringify(items, null, 1)};\n`);
fs.rmSync(new URL('../netlify/lib/starter-catalog.json', import.meta.url), { force: true });
console.log(`wrote ${items.length} starter products`);
